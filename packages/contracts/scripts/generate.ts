interface TsTypeResult {
  readonly expr: string;
  readonly imports: ReadonlySet<string>;
}

function tsStringLiteral(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function tsLiteral(value: unknown): string {
  if (value === null) return 'null';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return String(value);
  return tsStringLiteral(String(value));
}

function tsTypeOf(node: AnySchema): TsTypeResult {
  const name = lookupName(node, anyExportName, anyExportByStructure);
  if (name && EXPORTED_TYPE_NAMES.has(name)) {
    return { expr: name, imports: new Set([name]) };
  }

  if ('const' in node && node['const'] !== undefined) {
    return { expr: tsLiteral(node['const']), imports: new Set() };
  }

  const anyOf = node['anyOf'];
  if (Array.isArray(anyOf)) {
    const imports = new Set<string>();
    const parts = anyOf.filter(isSchemaObject).map((member) => {
      const resolved = tsTypeOf(member);
      for (const imported of resolved.imports) imports.add(imported);
      return resolved.expr;
    });
    return { expr: parts.length > 0 ? parts.join(' | ') : 'unknown', imports };
  }

  const type = node['type'];
  if (type === 'null') return { expr: 'null', imports: new Set() };
  if (type === 'string') return { expr: 'string', imports: new Set() };
  if (type === 'integer' || type === 'number') return { expr: 'number', imports: new Set() };
  if (type === 'boolean') return { expr: 'boolean', imports: new Set() };

  if (type === 'array') {
    const items = node['items'];
    if (isSchemaObject(items)) {
      const resolved = tsTypeOf(items);
      return { expr: `Array<${resolved.expr}>`, imports: resolved.imports };
    }
    return { expr: 'unknown[]', imports: new Set() };
  }

  if (type === 'object') {
    const properties = propertiesOf(node);
    const keys = schemaKeys(properties);
    if (keys.length > 0) {
      const required = requiredSet(node);
      const imports = new Set<string>();
      const members = keys.map((key) => {
        const resolved = tsTypeOf(properties[key] as AnySchema);
        for (const imported of resolved.imports) imports.add(imported);
        const optional = required.has(key) ? '' : '?';
        return `${key}${optional}: ${resolved.expr}`;
      });
      return { expr: `{ ${members.join('; ')} }`, imports };
    }
    const patternProperties = node['patternProperties'];
    if (isPlainObject(patternProperties)) {
      const first = schemaKeys(patternProperties)[0];
      if (first !== undefined && isSchemaObject(patternProperties[first])) {
        const resolved = tsTypeOf(patternProperties[first] as AnySchema);
        return { expr: `Record<string, ${resolved.expr}>`, imports: resolved.imports };
      }
    }
    const additional = node['additionalProperties'];
    if (isSchemaObject(additional)) {
      const resolved = tsTypeOf(additional);
      return { expr: `Record<string, ${resolved.expr}>`, imports: resolved.imports };
    }
    return { expr: 'Record<string, unknown>', imports: new Set() };
  }

  return { expr: 'unknown', imports: new Set() };
}

const CLIENT_PREAMBLE = `
/**
 * Typed fetch client for the Job Getter API, generated from
 * \`packages/contracts/src/routes.ts\`. One method per route operationId.
 *
 * Authentication is the HttpOnly session cookie, so every request is sent with
 * \`credentials: 'include'\`. Mutating routes additionally carry the anti-CSRF
 * token returned by \`getCsrfToken()\`, and the commands that the specification
 * marks as idempotent require an explicit \`idempotencyKey\` argument.
 */

export type FetchLike = (input: string, init?: RequestInit) => Promise<Response>;

export interface ApiClientOptions {
  /** Origin (and optional path prefix) the API is mounted on, e.g. \`https://localhost:8080\`. */
  readonly baseUrl: string;
  /** Injectable fetch implementation; defaults to \`globalThis.fetch\`. */
  readonly fetch?: FetchLike;
  /** Called once per 401 response, before the ApiError is thrown. */
  readonly onUnauthenticated?: () => void;
  /** Supplies the anti-CSRF token for routes that require one. */
  readonly getCsrfToken?: () => string | null | undefined;
}

/** Error envelope from 04_API_CONTRACTS.md. */
export interface ErrorEnvelopeBody {
  readonly error: {
    readonly code: string;
    readonly message: string;
    readonly fields?: Record<string, string>;
    readonly request_id?: string;
  };
}

/**
 * Thrown for every non-2xx response. \`code\` comes from the server envelope when
 * one was returned; a transport or non-JSON failure keeps the HTTP status and a
 * generic code rather than pretending the request succeeded.
 */
export class ApiError extends Error {
  readonly status: number;
  readonly code: ErrorCode | string;
  readonly fields: Record<string, string>;
  readonly requestId: string | null;

  constructor(init: {
    status: number;
    code: ErrorCode | string;
    message: string;
    fields?: Record<string, string>;
    requestId?: string | null;
  }) {
    super(init.message);
    this.name = 'ApiError';
    this.status = init.status;
    this.code = init.code;
    this.fields = init.fields ?? {};
    this.requestId = init.requestId ?? null;
  }

  static async fromResponse(response: Response): Promise<ApiError> {
    let payload: unknown;
    try {
      payload = await response.json();
    } catch {
      payload = undefined;
    }
    const envelope =
      typeof payload === 'object' && payload !== null && 'error' in payload
        ? (payload as ErrorEnvelopeBody).error
        : undefined;
    return new ApiError({
      status: response.status,
      code: envelope?.code ?? \`HTTP_\${response.status}\`,
      message: envelope?.message ?? \`Request failed with status \${response.status}\`,
      fields: envelope?.fields ?? {},
      requestId: envelope?.request_id ?? null,
    });
  }
}

type QueryValue = string | number | boolean | null | undefined;

interface RequestSpec {
  readonly method: string;
  readonly prefix: string;
  readonly path: string;
  readonly params?: Record<string, string>;
  readonly query?: Record<string, QueryValue>;
  readonly json?: unknown;
  readonly formData?: FormData;
  readonly csrf?: boolean;
  readonly idempotencyKey?: string;
  readonly binary?: boolean;
  readonly noContent?: boolean;
  readonly signal?: AbortSignal;
}

export class JobGetterApiClient {
  readonly #baseUrl: string;
  readonly #fetch: FetchLike;
  readonly #onUnauthenticated: (() => void) | undefined;
  readonly #getCsrfToken: (() => string | null | undefined) | undefined;

  constructor(options: ApiClientOptions) {
    this.#baseUrl = options.baseUrl.replace(/\\/+$/, '');
    this.#fetch = options.fetch ?? ((input, init) => globalThis.fetch(input, init));
    this.#onUnauthenticated = options.onUnauthenticated;
    this.#getCsrfToken = options.getCsrfToken;
  }

  async #request<T>(spec: RequestSpec): Promise<T> {
    let path = spec.path;
    for (const [key, value] of Object.entries(spec.params ?? {})) {
      path = path.replace(\`:\${key}\`, encodeURIComponent(String(value)));
    }

    let url = \`\${this.#baseUrl}\${spec.prefix}\${path}\`;
    const search = new URLSearchParams();
    for (const [key, value] of Object.entries(spec.query ?? {})) {
      if (value !== undefined && value !== null) search.append(key, String(value));
    }
    const queryString = search.toString();
    if (queryString.length > 0) url += \`?\${queryString}\`;

    const headers: Record<string, string> = {
      Accept: spec.binary ? 'application/octet-stream' : 'application/json',
    };
    let body: BodyInit | undefined;
    if (spec.formData !== undefined) {
      body = spec.formData;
    } else if (spec.json !== undefined) {
      headers['Content-Type'] = 'application/json';
      body = JSON.stringify(spec.json);
    }
    if (spec.csrf === true) {
      const token = this.#getCsrfToken?.();
      if (token !== undefined && token !== null && token !== '') headers['X-CSRF-Token'] = token;
    }
    if (spec.idempotencyKey !== undefined) headers['Idempotency-Key'] = spec.idempotencyKey;

    const response = await this.#fetch(url, {
      method: spec.method,
      credentials: 'include',
      headers,
      body,
      signal: spec.signal,
    });

    if (response.status === 401) this.#onUnauthenticated?.();
    if (!response.ok) throw await ApiError.fromResponse(response);
    if (spec.noContent === true || response.status === 204) return undefined as T;
    if (spec.binary === true) return (await response.blob()) as T;
    return (await response.json()) as T;
  }
`;

interface ClientBuild {
  readonly source: string;
}

export function buildClient(): ClientBuild {
  const typeImports = new Set<string>(['ErrorCode']);
  const aliases: string[] = [];
  const methods: string[] = [];

  const register = (result: TsTypeResult): string => {
    for (const imported of result.imports) typeImports.add(imported);
    return result.expr;
  };

  for (const route of ROUTES) {
    const base = pascalCase(route.operationId);
    const argsName = `${base}Args`;
    const resultName = `${base}Result`;

    const argMembers: string[] = [];
    let hasRequiredArg = false;

    if (route.params) {
      const expr = register(tsTypeOf(route.params as unknown as AnySchema));
      argMembers.push(`  /** Path parameters. */\n  readonly params: ${expr};`);
      hasRequiredArg = true;
    }
    if (route.query) {
      const expr = register(tsTypeOf(route.query as unknown as AnySchema));
      argMembers.push(`  /** Query string parameters. */\n  readonly query?: ${expr};`);
    }

    // A DELETE carries a body only when its route declares one; see
    // `deleteWorkspace` in src/routes.ts, whose password cannot go in a URL.
    const bodyless = route.method === 'GET' || (route.method === 'DELETE' && !route.body);
    const sendsEmptyBody = Boolean(route.body) && !bodyless && isEmptyClosedObject(route.body);
    const sendsBody = Boolean(route.body) && !bodyless && !sendsEmptyBody;
    if (sendsBody) {
      if (route.multipart) {
        argMembers.push(
          '  /** multipart/form-data payload; set the file part and its `purpose` field. */\n  readonly body: FormData;',
        );
      } else {
        const expr = register(tsTypeOf(route.body as unknown as AnySchema));
        argMembers.push(`  /** JSON request body. */\n  readonly body: ${expr};`);
      }
      hasRequiredArg = true;
    }
    if (route.requiresIdempotencyKey) {
      argMembers.push(
        '  /** Required: sent as the `Idempotency-Key` header (04_API_CONTRACTS.md). */\n  readonly idempotencyKey: string;',
      );
      hasRequiredArg = true;
    }
    argMembers.push('  readonly signal?: AbortSignal;');

    const returnExpr =
      route.successStatus === 204 || isNullSchema(route.response)
        ? 'void'
        : route.binaryResponse
          ? 'Blob'
          : register(tsTypeOf(route.response as unknown as AnySchema));

    aliases.push(
      `/** Arguments for \`${route.method} ${API_PREFIX}${route.path}\`. */\nexport interface ${argsName} {\n${argMembers.join('\n')}\n}`,
    );
    aliases.push(
      `/** Result of \`${camelCase(route.operationId)}\`. */\nexport type ${resultName} = ${returnExpr};`,
    );

    const specLines: string[] = [
      `      method: '${route.method}',`,
      `      prefix: API_PREFIX,`,
      `      path: ${tsStringLiteral(route.path)},`,
    ];
    if (route.params) specLines.push('      params: args.params,');
    if (route.query) specLines.push('      query: args.query,');
    if (sendsBody && route.multipart) specLines.push('      formData: args.body,');
    else if (sendsBody) specLines.push('      json: args.body,');
    else if (sendsEmptyBody) specLines.push('      json: {},');
    if (route.csrf) specLines.push('      csrf: true,');
    if (route.requiresIdempotencyKey) specLines.push('      idempotencyKey: args.idempotencyKey,');
    if (route.binaryResponse) specLines.push('      binary: true,');
    if (route.successStatus === 204 || isNullSchema(route.response)) {
      specLines.push('      noContent: true,');
    }
    specLines.push('      signal: args.signal,');

    const signature = hasRequiredArg ? `args: ${argsName}` : `args: ${argsName} = {}`;
    methods.push(
      [
        `  /** ${route.summary} (\`${route.method} ${API_PREFIX}${route.path}\`) */`,
        `  ${camelCase(route.operationId)}(${signature}): Promise<${resultName}> {`,
        `    return this.#request<${resultName}>({`,
        ...specLines,
        '    });',
        '  }',
      ].join('\n'),
    );
  }

  const importList = [...typeImports].sort();
  const source = [
    TS_HEADER,
    `import type {\n${importList.map((name) => `  ${name},`).join('\n')}\n} from '@job-getter/contracts';`,
    '',
    `/** Version prefix from \`packages/contracts/src/routes.ts\`. */`,
    `const API_PREFIX = ${tsStringLiteral(API_PREFIX)};`,
    '',
    CLIENT_PREAMBLE.trimStart().replace(/\n$/, ''),
    '',
    methods.join('\n\n'),
    '}',
    '',
    aliases.join('\n\n'),
    '',
  ].join('\n');

  return { source };
}

