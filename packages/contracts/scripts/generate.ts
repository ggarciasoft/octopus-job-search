/**
 * `\d` and `\w` are Unicode-aware in both Rust's regex crate (which backs
 * Pydantic's `pattern`) and Python's `re`, but ASCII-only in the JavaScript
 * patterns these contracts are written against. Emitting explicit classes
 * keeps the two runtimes from disagreeing on, say, an Arabic-Indic digit.
 */
function toPythonPattern(jsPattern: string): string {
  let out = '';
  let inClass = false;
  for (let index = 0; index < jsPattern.length; index += 1) {
    const char = jsPattern[index] as string;
    if (char === '\\') {
      const next = jsPattern[index + 1];
      if (next === 'd' || next === 'w') {
        const body = next === 'd' ? '0-9' : 'A-Za-z0-9_';
        out += inClass ? body : `[${body}]`;
        index += 1;
        continue;
      }
      out += char + (next ?? '');
      index += 1;
      continue;
    }
    if (char === '[') inClass = true;
    else if (char === ']') inClass = false;
    out += char;
  }
  return out;
}

/** A Python raw string literal may not end with an odd run of backslashes. */
function trailingBackslashes(value: string): number {
  let count = 0;
  for (let index = value.length - 1; index >= 0 && value[index] === '\\'; index -= 1) count += 1;
  return count;
}

function splitRawChunks(value: string, budget: number): string[] {
  const chunks: string[] = [];
  let index = 0;
  while (index < value.length) {
    let end = Math.min(index + budget, value.length);
    while (end > index + 1 && trailingBackslashes(value.slice(index, end)) % 2 === 1) end -= 1;
    chunks.push(value.slice(index, end));
    index = end;
  }
  return chunks;
}

/**
 * Raw string literal. Splitting only ever happens between literals, which
 * Python concatenates implicitly, so the resulting pattern is byte-identical.
 */
function pyRawString(value: string): string {
  if (value.includes('"') || trailingBackslashes(value) % 2 === 1) {
    return JSON.stringify(value);
  }
  return `r"${value}"`;
}

function pyRawStringAssignment(name: string, value: string): string[] {
  const single = `${name} = ${pyRawString(value)}`;
  if (single.length <= PY_LINE_LENGTH) return [single];
  const chunks = splitRawChunks(value, PY_LINE_LENGTH - 10);
  return [`${name} = (`, ...chunks.map((chunk) => `    ${pyRawString(chunk)}`), ')'];
}

/**
 * The string formats these contracts use. `uuid` and `date-time` are mirrored
 * from `src/formats.ts` so the Python worker enforces exactly what
 * `Value.Check` enforces; `binary` is an OpenAPI transport hint with no
 * runtime meaning and is deliberately not validated.
 */
const PY_FORMAT_ALIASES: Readonly<Record<string, string>> = {
  uuid: 'UuidString',
  'date-time': 'TimestampString',
};
const PY_IGNORED_FORMATS = new Set(['binary']);

/** Read the authoritative format patterns out of `src/formats.ts`. */
function readFormatPatterns(): { uuid: string; dateTime: string } {
  const source = readFileSync(join(CONTRACTS_DIR, 'src', 'formats.ts'), 'utf8');
  const read = (constName: string): string => {
    const match = new RegExp(`const\\s+${constName}\\s*=\\s*/(.*)/([a-z]*);`).exec(source);
    if (match === null) {
      throw new Error(
        `generate.ts could not read ${constName} from src/formats.ts. The Python models mirror ` +
          'those regular expressions; update the extraction here if the file changed shape.',
      );
    }
    const pattern = toPythonPattern(match[1] as string);
    return (match[2] as string).includes('i') ? `(?i)${pattern}` : pattern;
  };
  return { uuid: read('UUID_PATTERN'), dateTime: read('DATE_TIME_PATTERN') };
}

/**
 * JSON Schema constraints that must survive into Pydantic. Dropping these is
 * not a cosmetic loss: the worker would then believe its own models are
 * authoritative and emit results that only fail at the API boundary.
 */
function pyFieldArguments(node: AnySchema): string[] {
  const args: string[] = [];
  const type = node['type'];
  const num = (key: string): number | undefined =>
    typeof node[key] === 'number' ? (node[key] as number) : undefined;

  if (type === 'string') {
    const minLength = num('minLength');
    const maxLength = num('maxLength');
    if (minLength !== undefined) args.push(`min_length=${minLength}`);
    if (maxLength !== undefined) args.push(`max_length=${maxLength}`);
    if (typeof node['pattern'] === 'string') {
      args.push(`pattern=${pyRawString(toPythonPattern(node['pattern'] as string))}`);
    }
  } else if (type === 'integer' || type === 'number') {
    const minimum = num('minimum');
    const maximum = num('maximum');
    const exclusiveMinimum = num('exclusiveMinimum');
    const exclusiveMaximum = num('exclusiveMaximum');
    const multipleOf = num('multipleOf');
    if (minimum !== undefined) args.push(`ge=${minimum}`);
    if (maximum !== undefined) args.push(`le=${maximum}`);
    if (exclusiveMinimum !== undefined) args.push(`gt=${exclusiveMinimum}`);
    if (exclusiveMaximum !== undefined) args.push(`lt=${exclusiveMaximum}`);
    if (multipleOf !== undefined) args.push(`multiple_of=${multipleOf}`);
  } else if (type === 'array') {
    const minItems = num('minItems');
    const maxItems = num('maxItems');
    if (minItems !== undefined) args.push(`min_length=${minItems}`);
    if (maxItems !== undefined) args.push(`max_length=${maxItems}`);
  }
  return args;
}

function annotate(expr: string, args: string[]): string {
  if (args.length === 0) return expr;
  return `Annotated[${expr}, Field(${args.join(', ')})]`;
}

interface PyField {
  readonly name: string;
  readonly type: string;
  readonly optional: boolean;
}

interface PyModel {
  readonly name: string;
  readonly fields: PyField[];
  readonly forbidExtra: boolean;
  readonly deps: Set<string>;
  readonly order: number;
}

interface PyTypeResult {
  readonly expr: string;
  readonly deps: ReadonlySet<string>;
  readonly imports: ReadonlySet<string>;
}

function pyLiteral(value: unknown): string {
  if (value === null) return 'None';
  if (value === true) return 'True';
  if (value === false) return 'False';
  if (typeof value === 'number') return String(value);
  return JSON.stringify(String(value));
}

interface PythonBuild {
  readonly models: string;
  readonly enums: string;
  readonly constants: string;
  readonly init: string;
  readonly modelNames: string[];
  readonly aliasNames: string[];
  readonly enumNames: string[];
  readonly constantNames: string[];
}

export function buildPython(): PythonBuild {
  const usedAliases = new Set<string>();
  const models = new Map<string, PyModel>();
  const nameByNode = new Map<object, string>(exportedSchemaName);
  const nodeByName = new Map<string, object>();
  for (const [node, name] of exportedSchemaName) nodeByName.set(name, node);
  const building = new Set<string>();
  let order = 0;

  const uniqueName = (hint: string, node: object): string => {
    let candidate = hint;
    let suffix = 2;
    while (nodeByName.has(candidate) && nodeByName.get(candidate) !== node) {
      candidate = `${hint}${suffix}`;
      suffix += 1;
    }
    return candidate;
  };

  const ensureModel = (name: string, node: AnySchema): void => {
    if (models.has(name) || building.has(name)) return;
    building.add(name);
    const required = requiredSet(node);
    const properties = propertiesOf(node);
    const fields: PyField[] = [];
    const deps = new Set<string>();
    const imports = new Set<string>();
    for (const key of schemaKeys(properties)) {
      const child = properties[key] as AnySchema;
      const resolved = pyTypeOf(child, `${name}${pascalCase(key)}`);
      for (const dep of resolved.deps) deps.add(dep);
      for (const imported of resolved.imports) imports.add(imported);
      fields.push({ name: key, type: resolved.expr, optional: !required.has(key) });
    }
    building.delete(name);
    models.set(name, {
      name,
      fields,
      forbidExtra: node['additionalProperties'] === false,
      deps,
      order: order++,
    });
    modelImports.set(name, imports);
  };

  const modelImports = new Map<string, Set<string>>();

  const pyTypeOf = (node: AnySchema, hint: string): PyTypeResult => {
    const known = lookupName(node, nameByNode, exportedSchemaByStructure);
    if (known) {
      ensureModelForNamed(known, (nodeByName.get(known) as AnySchema | undefined) ?? node);
      return { expr: known, deps: new Set([known]), imports: new Set() };
    }

    if ('const' in node && node['const'] !== undefined) {
      return {
        expr: `Literal[${pyLiteral(node['const'])}]`,
        deps: new Set(),
        imports: new Set(['Literal']),
      };
    }

    const anyOf = node['anyOf'];
    if (Array.isArray(anyOf)) {
      const members = anyOf.filter(isSchemaObject);
      const nullable = members.some(
        (member) => member['type'] === 'null' && schemaKeys(member).length === 1,
      );
      const rest = members.filter(
        (member) => !(member['type'] === 'null' && schemaKeys(member).length === 1),
      );
      const deps = new Set<string>();
      const imports = new Set<string>();
      let expr: string;
      if (rest.length === 0) {
        expr = 'None';
      } else if (rest.every((member) => 'const' in member && member['const'] !== undefined)) {
        imports.add('Literal');
        expr = `Literal[${rest.map((member) => pyLiteral(member['const'])).join(', ')}]`;
      } else {
        const parts = rest.map((member, index) => {
          const memberHint = rest.length === 1 ? hint : `${hint}Variant${index + 1}`;
          const resolved = pyTypeOf(member, memberHint);
          for (const dep of resolved.deps) deps.add(dep);
          for (const imported of resolved.imports) imports.add(imported);
          return resolved.expr;
        });
        if (parts.length === 1) {
          expr = parts[0] as string;
        } else {
          imports.add('Union');
          expr = `Union[${parts.join(', ')}]`;
        }
      }
      if (nullable && expr !== 'None') expr = `${expr} | None`;
      return { expr, deps, imports };
    }

    const type = node['type'];
    if (type === 'null') return { expr: 'None', deps: new Set(), imports: new Set() };
    if (type === 'boolean') return { expr: 'bool', deps: new Set(), imports: new Set() };

    if (type === 'string') {
      const format = node['format'];
      if (typeof format === 'string' && !PY_IGNORED_FORMATS.has(format)) {
        const alias = PY_FORMAT_ALIASES[format];
        if (alias === undefined) {
          throw new Error(
            `Unhandled string format '${format}'. Add it to PY_FORMAT_ALIASES (and to ` +
              'src/formats.ts) or to PY_IGNORED_FORMATS if it is a transport hint only.',
          );
        }
        usedAliases.add(alias);
        // The alias already carries the format's pattern; anything else the
        // schema declares still applies on top of it.
        const extra = pyFieldArguments(node).filter((arg) => !arg.startsWith('pattern='));
        if (extra.length === 0) return { expr: alias, deps: new Set(), imports: new Set() };
        return {
          expr: annotate(alias, extra),
          deps: new Set(),
          imports: new Set(['Annotated', 'Field']),
        };
      }
      const args = pyFieldArguments(node);
      return {
        expr: annotate('str', args),
        deps: new Set(),
        imports: new Set(args.length > 0 ? ['Annotated', 'Field'] : []),
      };
    }

    if (type === 'integer' || type === 'number') {
      const args = pyFieldArguments(node);
      return {
        expr: annotate(type === 'integer' ? 'int' : 'float', args),
        deps: new Set(),
        imports: new Set(args.length > 0 ? ['Annotated', 'Field'] : []),
      };
    }

    if (type === 'array') {
      const args = pyFieldArguments(node);
      const items = node['items'];
      const inner = isSchemaObject(items)
        ? pyTypeOf(items, `${hint}Item`)
        : { expr: 'Any', deps: new Set<string>(), imports: new Set(['Any']) };
      const imports = new Set<string>(inner.imports);
      if (args.length > 0) {
        imports.add('Annotated');
        imports.add('Field');
      }
      return { expr: annotate(`list[${inner.expr}]`, args), deps: inner.deps, imports };
    }

    if (type === 'object') {
      if (Object.keys(propertiesOf(node)).length > 0) {
        const name = uniqueName(hint, node);
        nameByNode.set(node, name);
        nodeByName.set(name, node);
        ensureModel(name, node);
        return { expr: name, deps: new Set([name]), imports: new Set() };
      }
      const patternProperties = node['patternProperties'];
      if (isPlainObject(patternProperties)) {
        const first = schemaKeys(patternProperties)[0];
        if (first !== undefined && isSchemaObject(patternProperties[first])) {
          const resolved = pyTypeOf(patternProperties[first] as AnySchema, `${hint}Value`);
          return {
            expr: `dict[str, ${resolved.expr}]`,
            deps: resolved.deps,
            imports: resolved.imports,
          };
        }
      }
      const additional = node['additionalProperties'];
      if (isSchemaObject(additional)) {
        const resolved = pyTypeOf(additional, `${hint}Value`);
        return {
          expr: `dict[str, ${resolved.expr}]`,
          deps: resolved.deps,
          imports: resolved.imports,
        };
      }
      return { expr: 'dict[str, Any]', deps: new Set(), imports: new Set(['Any']) };
    }

    // No `type`, no `anyOf`, no `const`: Type.Unknown().
    return { expr: 'Any', deps: new Set(), imports: new Set(['Any']) };
  };

  const ensureModelForNamed = (name: string, node: AnySchema): void => {
    ensureModel(name, node);
  };

  for (const [name, schema] of Object.entries(EXPORTED_SCHEMAS)) {
    ensureModel(name, schema as unknown as AnySchema);
  }

  /* Dependency (topological) ordering, deterministic by creation order. */
  const emitted: PyModel[] = [];
  const done = new Set<string>();
  const pending = [...models.values()].sort((a, b) => a.order - b.order);
  while (pending.length > 0) {
    const index = pending.findIndex((model) =>
      [...model.deps].every((dep) => dep === model.name || done.has(dep)),
    );
    if (index === -1) {
      throw new Error(
        `Cyclic schema dependency among: ${pending.map((model) => model.name).join(', ')}`,
      );
    }
    const [next] = pending.splice(index, 1);
    const model = next as PyModel;
    emitted.push(model);
    done.add(model.name);
  }

  const allImports = new Set<string>();
  for (const model of emitted) {
    for (const imported of modelImports.get(model.name) ?? []) allImports.add(imported);
  }

  const TYPING_NAMES = new Set(['Annotated', 'Any', 'Literal', 'Union']);
  const typingImports = [...allImports].filter((name) => TYPING_NAMES.has(name)).sort();
  const pydanticImports = new Set(['BaseModel', 'ConfigDict']);
  if (allImports.has('Field')) pydanticImports.add('Field');

  const wantsUuid = usedAliases.has('UuidString');
  const wantsTimestamp = usedAliases.has('TimestampString');
  if (wantsUuid || wantsTimestamp) {
    typingImports.push('Annotated');
    pydanticImports.add('Field');
  }
  if (wantsTimestamp) pydanticImports.add('AfterValidator');
  const sortedTypingImports = [...new Set(typingImports)].sort();

  const lines: string[] = [PY_HEADER];
  lines.push('"""Pydantic v2 models generated from the authoritative TypeBox contracts.');
  lines.push('');
  lines.push('Every JSON Schema constraint - pattern, length, range, item count and string');
  lines.push('format - is carried through, so a worker that validates with these models');
  lines.push('reaches the same verdict as the API, instead of only failing at the boundary.');
  lines.push('"""');
  lines.push('');
  const stdlibImports: string[] = [];
  if (wantsTimestamp) stdlibImports.push('from datetime import datetime');
  if (sortedTypingImports.length > 0) {
    stdlibImports.push(`from typing import ${sortedTypingImports.join(', ')}`);
  }
  if (stdlibImports.length > 0) {
    lines.push(...stdlibImports);
    lines.push('');
  }
  lines.push(`from pydantic import ${[...pydanticImports].sort().join(', ')}`);

  if (wantsUuid || wantsTimestamp) {
    const patterns = readFormatPatterns();
    lines.push('');
    if (wantsTimestamp) {
      lines.push('');
      lines.push('def _validate_utc_timestamp(value: str) -> str:');
      lines.push('    # The pattern fixes the shape and the UTC-only offset. This additionally');
      lines.push(
        '    # rejects instants the calendar does not allow, such as 2026-02-30T00:00:00Z,',
      );
      lines.push('    # matching what registerContractFormats() enforces on the TypeScript side.');
      lines.push('    try:');
      lines.push('        datetime.fromisoformat(value)');
      lines.push('    except ValueError as error:');
      lines.push('        raise ValueError("not a valid UTC ISO-8601 instant") from error');
      lines.push('    return value');
      lines.push('');
    }
    lines.push('');
    lines.push('# Mirrored from packages/contracts/src/formats.ts so both runtimes agree.');
    if (wantsUuid) {
      lines.push(...pyRawStringAssignment('_UUID_PATTERN', patterns.uuid));
      lines.push('UuidString = Annotated[str, Field(pattern=_UUID_PATTERN)]');
    }
    if (wantsTimestamp) {
      lines.push(...pyRawStringAssignment('_TIMESTAMP_PATTERN', patterns.dateTime));
      lines.push('TimestampString = Annotated[');
      lines.push('    str,');
      lines.push('    Field(pattern=_TIMESTAMP_PATTERN),');
      lines.push('    AfterValidator(_validate_utc_timestamp),');
      lines.push(']');
    }
  }

  for (const model of emitted) {
    lines.push('');
    lines.push('');
    lines.push(`class ${model.name}(BaseModel):`);
    const configEntries: string[] = [];
    if (model.forbidExtra) configEntries.push('extra="forbid"');
    if (model.fields.some((field) => field.name.startsWith('model_'))) {
      configEntries.push('protected_namespaces=()');
    }
    if (configEntries.length > 0) {
      lines.push(`    model_config = ConfigDict(${configEntries.join(', ')})`);
      if (model.fields.length > 0) lines.push('');
    }
    if (model.fields.length === 0 && configEntries.length === 0) {
      lines.push('    pass');
      continue;
    }
    for (const field of model.fields) {
      const annotation = field.optional ? nullable(field.type) : field.type;
      lines.push(...pyFieldLines(field.name, annotation, field.optional));
    }
  }
  lines.push('');

  const modelsSource = lines.join('\n');

  /* enums.py */
  const enumLines: string[] = [PY_HEADER];
  enumLines.push('"""String enumerations generated from the authoritative TypeBox contracts."""');
  enumLines.push('');
  enumLines.push('from enum import StrEnum');
  const enumNames = Object.keys(EXPORTED_ENUMS);
  for (const name of enumNames) {
    enumLines.push('');
    enumLines.push('');
    enumLines.push(`class ${name}(StrEnum):`);
    const values = EXPORTED_ENUMS[name] as readonly string[];
    if (values.length === 0) {
      enumLines.push('    pass');
      continue;
    }
    for (const value of values) {
      enumLines.push(`    ${screamingSnakeCase(value)} = ${JSON.stringify(value)}`);
    }
  }
  enumLines.push('');

  /* constants.py */
  const constantLines: string[] = [PY_HEADER];
  constantLines.push('"""Shared constants generated from the authoritative TypeBox contracts."""');
  constantLines.push('');
  constantLines.push('from typing import Final');
  constantLines.push('');
  const constantNames = Object.keys(EXPORTED_CONSTANTS);
  for (const name of constantNames) {
    const value = (EXPORTED_CONSTANTS as Record<string, unknown>)[name];
    if (Array.isArray(value)) {
      const items = value.map((entry) => pyLiteral(entry));
      const tuple = items.length === 1 ? `(${items[0]},)` : `(${items.join(', ')})`;
      const oneLine = `${name}: Final = ${tuple}`;
      if (oneLine.length <= PY_LINE_LENGTH) {
        constantLines.push(oneLine);
      } else {
        // Wrap rather than emit a line Ruff will reject. A trailing comma on
        // the last item keeps `ruff format` from collapsing it back.
        constantLines.push(`${name}: Final = (`);
        for (const item of items) constantLines.push(`    ${item},`);
        constantLines.push(')');
      }
    } else {
      constantLines.push(`${name}: Final = ${pyLiteral(value)}`);
    }
  }
  constantLines.push('');

  /* __init__.py */
  const modelNames = emitted.map((model) => model.name);
  // The constrained string aliases live alongside the models so a worker can
  // validate a bare uuid or timestamp with the same rule the models use.
  const aliasNames = [...usedAliases].sort();
  const exportable = [...modelNames, ...aliasNames, ...enumNames, ...constantNames];
  // Ruff's RUF022 "isort-style" __all__ ordering: SCREAMING_SNAKE constants
  // first, then the CamelCase names, each group sorted.
  const allNames = [
    ...exportable.filter((name) => /^[A-Z0-9_]+$/.test(name)).sort(),
    ...exportable.filter((name) => !/^[A-Z0-9_]+$/.test(name)).sort(),
  ];
  const initLines: string[] = [PY_HEADER];
  initLines.push('"""Generated contract bindings for the Job Getter Python worker."""');
  initLines.push('');
  initLines.push(`from .constants import (`);
  for (const name of [...constantNames].sort()) initLines.push(`    ${name},`);
  initLines.push(')');
  initLines.push(`from .enums import (`);
  for (const name of [...enumNames].sort()) initLines.push(`    ${name},`);
  initLines.push(')');
  initLines.push(`from .models import (`);
  for (const name of [...modelNames, ...aliasNames].sort()) initLines.push(`    ${name},`);
  initLines.push(')');
  initLines.push('');
  initLines.push('__all__ = [');
  for (const name of allNames) initLines.push(`    ${JSON.stringify(name)},`);
  initLines.push(']');
  initLines.push('');

  return {
    models: modelsSource,
    enums: enumLines.join('\n'),
    constants: constantLines.join('\n'),
    init: initLines.join('\n'),
    modelNames,
    aliasNames,
    enumNames,
    constantNames,
  };
}

/** Add `| None` without producing `None | None` or a redundant `Any | None`. */
function nullable(expr: string): string {
  if (expr === 'None' || expr === 'Any') return expr;
  if (expr.endsWith(' | None')) return expr;
  return `${expr} | None`;
}

const PY_LINE_LENGTH = 100;

/** Split a bracket body on top-level commas. */
function splitTopLevel(body: string): string[] {
  const parts: string[] = [];
  let depth = 0;
  let quote: string | null = null;
  let current = '';
  for (const char of body) {
    if (quote !== null) {
      current += char;
      if (char === quote) quote = null;
      continue;
    }
    if (char === '"' || char === "'") {
      quote = char;
      current += char;
      continue;
    }
    if (char === '[' || char === '(') depth += 1;
    if (char === ']' || char === ')') depth -= 1;
    if (char === ',' && depth === 0) {
      parts.push(current.trim());
      current = '';
      continue;
    }
    current += char;
  }
  if (current.trim().length > 0) parts.push(current.trim());
  return parts;
}

/**
 * Render one Pydantic field, wrapping oversized `Literal[...]`/`Union[...]`
 * annotations inside their brackets so generated output stays within the Ruff
 * line length configured in services/worker/pyproject.toml.
 */
function wrapPyType(annotation: string, indent: string, overhead = 0): string[] {
  if (indent.length + overhead + annotation.length <= PY_LINE_LENGTH) {
    return [indent + annotation];
  }
  const match = /^(Annotated|Literal|Union|list|dict)\[(.*)\]((?: \| None)?)$/s.exec(annotation);
  if (!match) return [indent + annotation];
  const head = match[1] as string;
  const body = match[2] as string;
  const tail = match[3] as string;
  const parts = splitTopLevel(body);
  if (parts.length === 0) return [indent + annotation];

  const out = [`${indent}${head}[`];
  parts.forEach((part, index) => {
    const nested = wrapPyType(part, `${indent}    `, index < parts.length - 1 ? 1 : 0);
    if (index < parts.length - 1) {
      nested[nested.length - 1] = `${nested[nested.length - 1] as string},`;
    }
    out.push(...nested);
  });
  out.push(`${indent}]${tail}`);
  return out;
}

function pyFieldLines(name: string, annotation: string, hasDefault: boolean): string[] {
  const suffix = hasDefault ? ' = None' : '';
  const single = `    ${name}: ${annotation}${suffix}`;
  if (single.length <= PY_LINE_LENGTH) return [single];

  const wrapped = wrapPyType(annotation, '    ', name.length + 2 + suffix.length);
  if (wrapped.length === 1) return [single];
  wrapped[0] = `    ${name}: ${(wrapped[0] as string).trimStart()}`;
  wrapped[wrapped.length - 1] = `${wrapped[wrapped.length - 1] as string}${suffix}`;
  return wrapped;
}

