function main(argv: string[]): number {
  if (argv.includes('--check')) {
    const drift = checkArtifacts();
    if (drift.length === 0) {
      console.log(
        `contracts: generated artifacts are up to date (${buildArtifacts().size} files).`,
      );
      return 0;
    }
    console.error('contracts: generated artifacts are out of date.\n');
    for (const entry of drift) {
      console.error(`  ${entry.status.toUpperCase().padEnd(10)} ${entry.file}`);
      if (entry.detail) {
        for (const line of entry.detail.split('\n')) console.error(`    ${line}`);
      }
    }
    console.error('\nRun `pnpm contracts:generate` and commit the result.');
    return 1;
  }

  const { written, removed } = writeArtifacts();
  for (const file of removed) console.log(`removed ${file}`);
  console.log(`contracts: wrote ${written.length} generated files.`);
  return 0;
}

