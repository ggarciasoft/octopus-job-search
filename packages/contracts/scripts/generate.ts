const ERROR_RESPONSES: ReadonlyArray<readonly [string, string]> = [
  ['400', 'Malformed request body, query or header.'],
  ['401', 'Unauthenticated: no valid session, device token or worker credential.'],
  ['403', 'Authenticated but not permitted for this workspace resource.'],
  ['404', 'Absent or not accessible from the authenticated workspace.'],
  [
    '409',
    'Conflict: stale revision, duplicate command or idempotency key reuse with a different body.',
  ],
  ['413', 'Payload exceeds the configured upload limit.'],
  ['422', 'Structurally valid but invalid domain input.'],
  ['429', 'Quota or rate limit exceeded.'],
];

interface OpenApiBuild {
  document: JsonSchema;
}

function openApiPath(prefix: string, path: string): string {
  return prefix + path.replace(/:([A-Za-z0-9_]+)/g, '{$1}');
}

function tagForPath(path: string): string {
  const segment = path.split('/').filter(Boolean)[0];
  return segment ? segment.replace(/[^A-Za-z0-9_-]/g, '') : 'root';
}

function securityFor(auth: RouteDefinition['auth']): JsonValue[] {
  switch (auth) {
    case 'public':
      return [];
    case 'session':
      return [{ sessionCookie: [] }];
    case 'device':
      return [{ deviceToken: [] }];
    case 'worker':
      return [{ workerToken: [] }];
    default:
      throw new Error(`Unhandled auth mode: ${String(auth)}`);
  }
}

/** Empty closed object: `{}` request bodies documented as such. */
function isEmptyClosedObject(schema: TSchema | undefined): boolean {
  if (!schema) return false;
  const node = schema as unknown as AnySchema;
  if (node['type'] !== 'object') return false;
  if (node['additionalProperties'] !== false) return false;
  return Object.keys(propertiesOf(node)).length === 0;
}

function isNullSchema(schema: TSchema | undefined): boolean {
  if (!schema) return false;
  return (schema as unknown as AnySchema)['type'] === 'null';
}

export function buildOpenApiDocument(): JsonSchema {
  const components = new Map<string, JsonSchema>();
  const inFlight = new Set<string>();

  const convert = (node: AnySchema): JsonSchema => {
    const name = lookupName(node, exportedSchemaName, exportedSchemaByStructure);
    if (name) {
      register(name, node);
      return { $ref: `#/components/schemas/${name}` };
    }
    return convertBody(node);
  };

  const convertBody = (node: AnySchema): JsonSchema => {
    const out: JsonSchema = {};
    for (const key of schemaKeys(node)) {
      const value = node[key];
      if (NESTED_SCHEMA_KEYS.includes(key) && isSchemaObject(value)) {
        out[key] = convert(value);
      } else if (NESTED_SCHEMA_LISTS.includes(key) && Array.isArray(value)) {
        out[key] = value.map((entry) =>
          isSchemaObject(entry) ? convert(entry) : deepClone(entry),
        );
      } else if (NESTED_SCHEMA_MAPS.includes(key) && isPlainObject(value)) {
        const mapped: JsonSchema = {};
        for (const child of schemaKeys(value)) {
          const childValue = value[child];
          mapped[child] = isSchemaObject(childValue) ? convert(childValue) : deepClone(childValue);
        }
        out[key] = mapped;
      } else {
        out[key] = deepClone(value);
      }
    }
    return out;
  };

  const register = (name: string, node: AnySchema): void => {
    if (components.has(name) || inFlight.has(name)) return;
    inFlight.add(name);
    const body = convertBody(node);
    inFlight.delete(name);
    components.set(name, body);
  };

  // Emit every exported schema so the document is a complete catalogue and
  // each one is referenced rather than duplicated.
  for (const [name, schema] of Object.entries(EXPORTED_SCHEMAS)) {
    register(name, schema as unknown as AnySchema);
  }

  const ref = (name: string): JsonSchema => ({ $ref: `#/components/schemas/${name}` });

  const errorResponses = (): JsonSchema => {
    const out: JsonSchema = {};
    for (const [status, description] of ERROR_RESPONSES) {
      out[status] = {
        description,
        content: { 'application/json': { schema: ref('ErrorEnvelope') } },
      };
    }
    return out;
  };

  const parametersFor = (route: RouteDefinition): JsonValue[] => {
    const parameters: JsonValue[] = [];
    if (route.params) {
      const node = route.params as unknown as AnySchema;
      const required = requiredSet(node);
      const properties = propertiesOf(node);
      for (const key of schemaKeys(properties)) {
        parameters.push({
          name: key,
          in: 'path',
          required: true,
          description: required.has(key) ? undefined : 'Path parameters are always required.',
          schema: convert(properties[key] as AnySchema),
        });
      }
    }
    if (route.query) {
      const node = route.query as unknown as AnySchema;
      const required = requiredSet(node);
      const properties = propertiesOf(node);
      for (const key of schemaKeys(properties)) {
        parameters.push({
          name: key,
          in: 'query',
          required: required.has(key),
          schema: convert(properties[key] as AnySchema),
        });
      }
    }
    if (route.requiresIdempotencyKey) {
      parameters.push({
        name: 'Idempotency-Key',
        in: 'header',
        required: true,
        description:
          'Mandatory for this command. Replaying the same key returns the stored response for 24 hours; reusing it with a different body returns 409.',
        schema: { type: 'string', minLength: 8, maxLength: 200 },
      });
    }
    if (route.csrf) {
      parameters.push({
        name: 'X-CSRF-Token',
        in: 'header',
        required: true,
        description: 'Anti-CSRF token for cookie-authenticated mutations; origin is verified too.',
        schema: { type: 'string', minLength: 8, maxLength: 200 },
      });
    }
    return parameters.map((parameter) => {
      const clean: JsonSchema = {};
      for (const [key, value] of Object.entries(parameter as AnySchema)) {
        if (value !== undefined) clean[key] = value;
      }
      return clean;
    });
  };

  const requestBodyFor = (route: RouteDefinition): JsonValue | undefined => {
    // A DELETE carries a body only when its route declares one; see
    // `deleteWorkspace` in src/routes.ts, whose password cannot go in a URL.
    const bodyless = route.method === 'GET' || (route.method === 'DELETE' && !route.body);
    if (!route.body || bodyless) return undefined;
    if (route.multipart) {
      return {
        required: true,
        description: 'multipart/form-data upload. Fields are form parts, not a JSON document.',
        content: {
          'multipart/form-data': {
            schema: convert(route.body as unknown as AnySchema),
          },
        },
      };
    }
    return {
      required: !isEmptyClosedObject(route.body),
      content: { 'application/json': { schema: convert(route.body as unknown as AnySchema) } },
    };
  };

  const successResponseFor = (route: RouteDefinition): JsonSchema => {
    if (route.successStatus === 204 || isNullSchema(route.response)) {
      return { description: `${route.summary} Returns no content.` };
    }
    if (route.binaryResponse) {
      return {
        description: `${route.summary} Streamed attachment.`,
        content: {
          'application/octet-stream': { schema: { type: 'string', format: 'binary' } },
        },
      };
    }
    return {
      description: route.summary,
      content: {
        'application/json': { schema: convert(route.response as unknown as AnySchema) },
      },
    };
  };

  const paths: JsonSchema = {};
  const addOperation = (path: string, method: string, operation: JsonValue): void => {
    const existing = isPlainObject(paths[path]) ? (paths[path] as JsonSchema) : {};
    const key = method.toLowerCase();
    if (existing[key] !== undefined) {
      throw new Error(`Duplicate operation ${method} ${path}`);
    }
    existing[key] = operation;
    paths[path] = existing;
  };

  for (const route of ROUTES) {
    const parameters = parametersFor(route);
    const requestBody = requestBodyFor(route);
    const operation: JsonSchema = {
      operationId: route.operationId,
      summary: route.summary,
      tags: [tagForPath(route.path)],
      security: securityFor(route.auth),
      responses: {
        [String(route.successStatus)]: successResponseFor(route),
        ...errorResponses(),
      },
    };
    if (parameters.length > 0) operation['parameters'] = parameters;
    if (requestBody !== undefined) operation['requestBody'] = requestBody;
    addOperation(openApiPath(API_PREFIX, route.path), route.method, operation);
  }

  /* Internal worker protocol (04_API_CONTRACTS.md, "Internal task protocol"). */
  const INTERNAL_NOTE =
    'Internal worker protocol. Not publicly routable: it is served on the internal listener only and authenticated with the operator worker credential, never a user device token.';

  interface InternalOperation {
    readonly operationId: string;
    readonly method: 'GET' | 'POST';
    readonly path: string;
    readonly summary: string;
    readonly pathParams?: readonly string[];
    readonly body?: TSchema;
    readonly multipart?: boolean;
    readonly successStatus: 200 | 201 | 204;
    readonly response?: TSchema;
    readonly binaryResponse?: boolean;
    readonly extraResponses?: Readonly<Record<string, string>>;
  }

  const INTERNAL_OPERATIONS: readonly InternalOperation[] = [
    {
      operationId: 'claimTask',
      method: 'POST',
      path: '/tasks/claim',
      summary: 'Claim the next eligible task for the declared capabilities.',
      body: Protocol.ClaimRequest,
      successStatus: 200,
      response: Protocol.ClaimResponse,
      extraResponses: { '204': 'No eligible task is currently queued.' },
    },
    {
      operationId: 'heartbeatTask',
      method: 'POST',
      path: '/tasks/{id}/heartbeat',
      summary: 'Extend the lease and report progress; learns about cancellation.',
      pathParams: ['id'],
      body: Protocol.HeartbeatRequest,
      successStatus: 200,
      response: Protocol.HeartbeatResponse,
    },
    {
      operationId: 'completeTask',
      method: 'POST',
      path: '/tasks/{id}/complete',
      summary: 'Submit a task result; the API validates it inside the completing transaction.',
      pathParams: ['id'],
      body: Protocol.CompleteRequest,
      successStatus: 200,
      response: Protocol.TaskAck,
    },
    {
      operationId: 'failTask',
      method: 'POST',
      path: '/tasks/{id}/fail',
      summary: 'Report a failure. The server, not the worker, decides whether a retry happens.',
      pathParams: ['id'],
      body: Protocol.FailRequest,
      successStatus: 200,
      response: Protocol.TaskAck,
    },
    {
      operationId: 'downloadTaskInputFile',
      method: 'GET',
      path: '/tasks/{id}/files/{file_id}',
      summary: 'Download a declared task input file under the active lease.',
      pathParams: ['id', 'file_id'],
      successStatus: 200,
      binaryResponse: true,
    },
    {
      operationId: 'uploadTaskArtifact',
      method: 'POST',
      path: '/tasks/{id}/artifacts',
      summary: 'Upload a scoped, staged output artifact for this task.',
      pathParams: ['id'],
      multipart: true,
      successStatus: 201,
      response: Protocol.ArtifactUploadResponse,
    },
  ];

  for (const operation of INTERNAL_OPERATIONS) {
    const parameters: JsonValue[] = (operation.pathParams ?? []).map((name) => ({
      name,
      in: 'path',
      required: true,
      schema: { type: 'string', format: 'uuid' },
    }));
    parameters.push({
      name: 'Authorization',
      in: 'header',
      required: true,
      description: 'Bearer <worker credential>. Lease ownership is checked per task as well.',
      schema: { type: 'string' },
    });

    const responses: JsonSchema = {};
    if (operation.binaryResponse) {
      responses[String(operation.successStatus)] = {
        description: `${operation.summary} Streamed attachment.`,
        content: { 'application/octet-stream': { schema: { type: 'string', format: 'binary' } } },
      };
    } else if (operation.response) {
      responses[String(operation.successStatus)] = {
        description: operation.summary,
        content: {
          'application/json': { schema: convert(operation.response as unknown as AnySchema) },
        },
      };
    } else {
      responses[String(operation.successStatus)] = { description: operation.summary };
    }
    for (const [status, description] of Object.entries(operation.extraResponses ?? {})) {
      responses[status] = { description };
    }
    for (const [status, description] of ERROR_RESPONSES) {
      responses[status] = {
        description,
        content: { 'application/json': { schema: ref('ErrorEnvelope') } },
      };
    }

    const built: JsonSchema = {
      operationId: operation.operationId,
      summary: operation.summary,
      description: INTERNAL_NOTE,
      tags: ['internal'],
      security: [{ workerToken: [] }],
      parameters,
      responses,
    };
    if (operation.multipart) {
      built['requestBody'] = {
        required: true,
        description: 'multipart/form-data artifact upload scoped to this task.',
        content: { 'multipart/form-data': { schema: { type: 'object' } } },
      };
    } else if (operation.body) {
      built['requestBody'] = {
        required: true,
        content: {
          'application/json': { schema: convert(operation.body as unknown as AnySchema) },
        },
      };
    }
    addOperation(INTERNAL_PREFIX + operation.path, operation.method, built);
  }

  const packageJson = JSON.parse(readFileSync(join(CONTRACTS_DIR, 'package.json'), 'utf8')) as {
    version?: string;
  };

  const sortedComponents: JsonSchema = {};
  for (const name of [...components.keys()].sort()) {
    sortedComponents[name] = components.get(name) as JsonSchema;
  }

  return {
    openapi: '3.1.0',
    info: {
      title: 'Job Getter API',
      version: packageJson.version ?? '0.0.0',
      description:
        `Generated from the TypeBox contracts in packages/contracts by ${GENERATED_BY}. ` +
        'Do not edit by hand. JSON snake_case, ISO-8601 UTC timestamps, UUID identifiers. ' +
        'The API derives the workspace from the authenticated principal and never trusts a client workspace_id.',
    },
    tags: [...new Set(ROUTES.map((route) => tagForPath(route.path)))]
      .sort()
      .map((name) => ({ name }))
      .concat([{ name: 'internal' }]),
    components: {
      securitySchemes: {
        sessionCookie: {
          type: 'apiKey',
          in: 'cookie',
          name: 'jg_session',
          description: 'HttpOnly session cookie issued by POST /auth/login.',
        },
        deviceToken: {
          type: 'http',
          scheme: 'bearer',
          description:
            'Scoped device token for the extension or local runner; expires after 30 days.',
        },
        workerToken: {
          type: 'http',
          scheme: 'bearer',
          description: 'Operator worker credential for the internal task protocol only.',
        },
      },
      schemas: sortedComponents,
    },
    paths,
  };
}

