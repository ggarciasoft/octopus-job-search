type JsonValue = unknown;

interface JsonSchema {
  [key: string]: JsonValue;
}

type AnySchema = Record<string, JsonValue>;

/** Keys whose value is a single nested schema. */
const NESTED_SCHEMA_KEYS = ['items', 'not', 'propertyNames', 'contains', 'additionalProperties'];
/** Keys whose value is an array of nested schemas. */
const NESTED_SCHEMA_LISTS = ['anyOf', 'allOf', 'oneOf', 'prefixItems'];
/** Keys whose value is a record of nested schemas. */
const NESTED_SCHEMA_MAPS = ['properties', 'patternProperties', '$defs', 'definitions'];

function isPlainObject(value: unknown): value is AnySchema {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function isSchemaObject(value: unknown): value is AnySchema {
  return isPlainObject(value);
}

function isTypeBoxSchema(value: unknown): value is TSchema {
  return isPlainObject(value) && Kind in value;
}

/** Own string keys with a defined value, in declaration order. */
function schemaKeys(node: AnySchema): string[] {
  return Object.keys(node).filter((key) => node[key] !== undefined);
}

function deepClone<T>(value: T): T {
  return JSON.parse(JSON.stringify(value)) as T;
}

function requiredSet(node: AnySchema): Set<string> {
  const required = node['required'];
  return new Set(Array.isArray(required) ? (required as string[]) : []);
}

function propertiesOf(node: AnySchema): AnySchema {
  const properties = node['properties'];
  return isPlainObject(properties) ? properties : {};
}

