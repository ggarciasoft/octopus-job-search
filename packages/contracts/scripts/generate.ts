function serializeJson(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function normalizeText(value: string): string {
  const withoutCr = value.replace(/\r\n/g, '\n');
  return withoutCr.endsWith('\n') ? withoutCr : `${withoutCr}\n`;
}

/** Absolute path -> exact file contents. Deterministic for a given source tree. */
export function buildArtifacts(): Map<string, string> {
  const artifacts = new Map<string, string>();

  for (const name of Object.keys(EXPORTED_SCHEMAS).sort()) {
    const schema = EXPORTED_SCHEMAS[name] as TSchema;
    artifacts.set(
      join(SCHEMA_DIR, `${name}.schema.json`),
      serializeJson(buildJsonSchemaDocument(name, schema)),
    );
  }

  artifacts.set(OPENAPI_FILE, serializeJson(buildOpenApiDocument()));

  const python = buildPython();
  artifacts.set(join(PYTHON_DIR, 'models.py'), normalizeText(python.models));
  artifacts.set(join(PYTHON_DIR, 'enums.py'), normalizeText(python.enums));
  artifacts.set(join(PYTHON_DIR, 'constants.py'), normalizeText(python.constants));
  artifacts.set(join(PYTHON_DIR, '__init__.py'), normalizeText(python.init));

  artifacts.set(CLIENT_FILE, normalizeText(buildClient().source));

  return new Map([...artifacts.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1)));
}

function listExistingManagedFiles(): string[] {
  const found: string[] = [];
  // Build caches are not artifacts; they must not look like drift.
  const IGNORED_DIRECTORIES = new Set(['__pycache__', '.mypy_cache', '.ruff_cache']);
  const walk = (dir: string): void => {
    if (!existsSync(dir)) return;
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) {
        if (!IGNORED_DIRECTORIES.has(entry.name)) walk(full);
      } else if (!entry.name.endsWith('.pyc')) {
        found.push(full);
      }
    }
  };
  for (const dir of MANAGED_DIRECTORIES) walk(dir);
  if (existsSync(OPENAPI_FILE) && statSync(OPENAPI_FILE).isFile()) found.push(OPENAPI_FILE);
  return found.sort();
}

function displayPath(absolute: string): string {
  return relative(REPO_ROOT, absolute).split(sep).join(posix.sep);
}

export interface DriftEntry {
  readonly file: string;
  readonly status: 'missing' | 'changed' | 'unexpected';
  readonly detail?: string;
}

function firstDifference(expected: string, actual: string): string {
  const expectedLines = expected.split('\n');
  const actualLines = actual.split('\n');
  const limit = Math.max(expectedLines.length, actualLines.length);
  for (let index = 0; index < limit; index += 1) {
    if (expectedLines[index] !== actualLines[index]) {
      return [
        `first difference at line ${index + 1}`,
        `  generated: ${JSON.stringify(expectedLines[index] ?? '<end of file>')}`,
        `  on disk:   ${JSON.stringify(actualLines[index] ?? '<end of file>')}`,
      ].join('\n');
    }
  }
  return 'contents differ only in trailing whitespace';
}

/** Regenerate in memory and report every on-disk difference. */
export function checkArtifacts(): DriftEntry[] {
  const artifacts = buildArtifacts();
  const drift: DriftEntry[] = [];

  for (const [path, expected] of artifacts) {
    if (!existsSync(path)) {
      drift.push({ file: displayPath(path), status: 'missing' });
      continue;
    }
    const actual = readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
    if (actual !== expected) {
      drift.push({
        file: displayPath(path),
        status: 'changed',
        detail: firstDifference(expected, actual),
      });
    }
  }

  for (const path of listExistingManagedFiles()) {
    if (!artifacts.has(path)) {
      drift.push({ file: displayPath(path), status: 'unexpected' });
    }
  }

  return drift;
}

export function writeArtifacts(): { written: string[]; removed: string[] } {
  const artifacts = buildArtifacts();
  const written: string[] = [];
  const removed: string[] = [];

  for (const path of listExistingManagedFiles()) {
    if (!artifacts.has(path)) {
      rmSync(path);
      removed.push(displayPath(path));
    }
  }

  for (const [path, contents] of artifacts) {
    mkdirSync(dirname(path), { recursive: true });
    const current = existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n') : null;
    if (current !== contents) writeFileSync(path, contents, 'utf8');
    written.push(displayPath(path));
  }

  return { written, removed };
}

