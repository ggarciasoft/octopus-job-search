function pascalCase(value: string): string {
  return value
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

function camelCase(value: string): string {
  const pascal = pascalCase(value);
  return pascal.charAt(0).toLowerCase() + pascal.slice(1);
}

function screamingSnakeCase(value: string): string {
  return value
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^A-Za-z0-9]+/g, '_')
    .toUpperCase();
}

/** Identity map: TypeBox schema object -> exported name. */
function buildIdentityMap(): {
  exportedSchemaName: Map<object, string>;
  anyExportName: Map<object, string>;
} {
  const exportedSchemaName = new Map<object, string>();
  for (const [name, schema] of Object.entries(EXPORTED_SCHEMAS)) {
    if (!exportedSchemaName.has(schema)) exportedSchemaName.set(schema, name);
  }
  const anyExportName = new Map<object, string>(exportedSchemaName);
  for (const [name, value] of Object.entries(Contracts)) {
    if (isTypeBoxSchema(value) && !anyExportName.has(value)) anyExportName.set(value, name);
  }
  return { exportedSchemaName, anyExportName };
}

const { exportedSchemaName, anyExportName } = buildIdentityMap();

/**
 * Structural fallback for the identity map. `Type.Optional(ContactValue)` clones
 * the schema, so identity alone would emit a duplicate model for a nested object
 * that is byte-for-byte an exported one. Canonical JSON keys close that hole.
 */
function canonicalKey(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(canonicalKey).join(',')}]`;
  if (isPlainObject(value)) {
    const keys = schemaKeys(value).sort();
    return `{${keys.map((key) => `${JSON.stringify(key)}:${canonicalKey(value[key])}`).join(',')}}`;
  }
  return JSON.stringify(value ?? null);
}

function buildStructureMap(source: Map<object, string>): Map<string, string> {
  const structure = new Map<string, string>();
  for (const [node, name] of source) {
    const key = canonicalKey(node);
    if (!structure.has(key)) structure.set(key, name);
  }
  return structure;
}

const exportedSchemaByStructure = buildStructureMap(exportedSchemaName);
const anyExportByStructure = buildStructureMap(anyExportName);

/** Exported name for a schema node, by object identity first and shape second. */
function lookupName(
  node: AnySchema,
  byIdentity: Map<object, string>,
  byStructure: Map<string, string>,
): string | undefined {
  return byIdentity.get(node) ?? byStructure.get(canonicalKey(node));
}

/**
 * TypeScript type names re-exported from `@job-getter/contracts`. The generated
 * client cannot resolve `@sinclair/typebox` itself, so it imports the aliases
 * that `src/**` already declares as `Static<typeof Schema>`.
 */
function collectExportedTypeNames(): Set<string> {
  const names = new Set<string>();
  const walk = (dir: string): void => {
    for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
      a.name < b.name ? -1 : 1,
    )) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.name.endsWith('.ts')) {
        const source = readFileSync(full, 'utf8');
        for (const match of source.matchAll(/^export\s+(?:type|interface)\s+([A-Za-z0-9_]+)/gm)) {
          names.add(match[1] as string);
        }
      }
    }
  };
  walk(join(CONTRACTS_DIR, 'src'));
  return names;
}

const EXPORTED_TYPE_NAMES = collectExportedTypeNames();

