export function buildJsonSchemaDocument(name: string, schema: TSchema): JsonSchema {
  const body = deepClone(schema) as AnySchema;
  delete body['$schema'];
  delete body['$id'];
  delete body['title'];
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: `${SCHEMA_ID_BASE}/${name}.schema.json`,
    title: name,
    ...body,
  };
}

